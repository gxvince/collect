// 示例仅使用虚构值；新增路由时必须同步目录，覆盖测试会检查遗漏。
const site = { site_id: 'site_example' };
const paging = { page: 1, page_size: 20 };
const logged = '登录用户';
const admin = '仅管理员';
const scoped = '登录用户；普通用户需站点授权，页面相关操作还需页面权限';
const example = (
  body = {},
  bodyType = 'json',
  query = {},
  params = {},
  label = '默认示例',
) => ({ label, bodyType, body, query, params });
const get = (
  group,
  path,
  title,
  query = {},
  description = '无额外参数。',
  auth = logged,
  params = {},
) => ({
  group,
  method: 'GET',
  path,
  title,
  description,
  auth,
  examples: [example({}, 'none', query, params)],
});
const post = (
  group,
  path,
  title,
  body,
  description,
  auth = logged,
  bodyType = 'json',
) => ({
  group,
  method: 'POST',
  path,
  title,
  description,
  auth,
  examples: [example(body, bodyType)],
});
const proxyGet = (
  route,
  title,
  query = {},
  description = 'site_id 必填，指定已授权站点。',
  params = {},
) =>
  get(
    'WordPress 代理',
    `/api/proxy/${route}`,
    title,
    { ...site, ...query },
    description,
    scoped,
    params,
  );
const proxyPost = (route, title, body, description, bodyType = 'json') =>
  post(
    'WordPress 代理',
    `/api/proxy/${route}`,
    title,
    { ...site, ...body },
    description,
    scoped,
    bodyType,
  );

